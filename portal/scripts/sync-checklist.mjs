// ------- Keep the portal's checklist in step with the marketing site -------
// The website (../src/data) is the one place plans and checklist items are edited.
// This copies them in before every dev run and build, so the tech's checklist and
// the public checklist page can never drift apart. If the site files are not
// there (portal deployed alone), the committed copies are used as they are.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const from = join(here, '..', '..', 'src', 'data');
const to = join(here, '..', 'src', 'data');
const banner = '// GENERATED by scripts/sync-checklist.mjs. Edit ../src/data in the website instead.\n\n';

mkdirSync(to, { recursive: true });
for (const file of ['checklist.ts', 'plans.ts']) {
  const source = join(from, file);
  if (!existsSync(source)) {
    console.log(`sync-checklist: ${file} not found beside the portal, keeping the committed copy`);
    continue;
  }
  const next = banner + readFileSync(source, 'utf8');
  const target = join(to, file);
  if (!existsSync(target) || readFileSync(target, 'utf8') !== next) {
    writeFileSync(target, next);
    console.log(`sync-checklist: updated ${file}`);
  }
}
